import Foundation

/// Generates a self-contained static HTML "project page" for a paper (title, conference, abstract,
/// GitHub link) — the kind of single-page site academic papers link to for their code release.
/// The user pushes the output to GitHub Pages (or hosts it anywhere) themselves; this only
/// produces the file.
enum ProjectPageGenerator {
    static func generate(paper: Paper, abstract: String?) -> Data {
        let html = """
        <!doctype html>
        <html lang="en">
        <head>
        <meta charset="utf-8">
        <meta name="viewport" content="width=device-width, initial-scale=1">
        <title>\(escape(paper.title))</title>
        <style>
          :root { color-scheme: light dark; }
          body {
            font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif;
            max-width: 760px; margin: 0 auto; padding: 48px 24px; line-height: 1.6;
            color: #1a1a1a; background: #ffffff;
          }
          @media (prefers-color-scheme: dark) { body { color: #eaeaea; background: #121212; } }
          h1 { font-size: 1.9em; margin-bottom: 0.2em; }
          .meta { color: #767676; margin-bottom: 2em; }
          .links a {
            display: inline-block; margin: 0 10px 10px 0; padding: 8px 16px;
            border: 1px solid currentColor; border-radius: 6px; text-decoration: none; color: inherit;
          }
          .links a:hover { opacity: 0.7; }
          section { margin-top: 2.2em; }
          h2 { font-size: 1.15em; text-transform: uppercase; letter-spacing: 0.04em; color: #767676; }
        </style>
        </head>
        <body>
          <h1>\(escape(paper.title))</h1>
          \(metaLine(paper))
          <div class="links">
            \(linkButtons(paper))
          </div>
          \(abstractSection(abstract))
          <section>
            <p style="color:#767676; font-size: 0.9em;">Generated by Maziar.</p>
          </section>
        </body>
        </html>
        """
        return Data(html.utf8)
    }

    private static func metaLine(_ paper: Paper) -> String {
        guard let conference = paper.conferenceName, !conference.isEmpty else { return "" }
        return "<p class=\"meta\">\(escape(conference))</p>"
    }

    private static func linkButtons(_ paper: Paper) -> String {
        var links: [String] = []
        if let repoURL = paper.githubRepoURL {
            links.append("<a href=\"\(escape(repoURL.absoluteString))\">Code</a>")
        }
        return links.joined(separator: "\n            ")
    }

    private static func abstractSection(_ abstract: String?) -> String {
        guard let abstract, !abstract.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return "" }
        return """
        <section>
            <h2>Abstract</h2>
            <p>\(escape(abstract))</p>
          </section>
        """
    }

    private static func escape(_ text: String) -> String {
        text
            .replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
    }
}
